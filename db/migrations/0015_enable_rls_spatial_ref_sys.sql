-- 0015_enable_rls_spatial_ref_sys.sql
-- Vegar's Diamond — Silence Supabase ERROR-level advisor on spatial_ref_sys
--
-- Background
-- ----------
-- The Supabase advisor (run 2026-05-17) raised one ERROR-level finding:
--
--   [ERROR] rls_disabled_in_public
--     public.spatial_ref_sys — RLS not enabled
--
-- spatial_ref_sys is the PostGIS reference catalog of spatial reference
-- systems (EPSG codes and similar). It is owned by `supabase_admin`,
-- created automatically by the postgis extension (extension_owned = 1),
-- and contains ~8,500 rows of publicly published coordinate-system
-- definitions. The data itself is not sensitive.
--
-- The linter flags it regardless because any table in the `public`
-- schema that is exposed via PostgREST without RLS counts as
-- "publicly readable" and trips the ERROR-level rule
-- `0013_rls_disabled_in_public`:
--
--   https://supabase.com/docs/guides/database/database-linter?lint=0013_rls_disabled_in_public
--
-- What this migration does
-- ------------------------
-- Enables RLS on `public.spatial_ref_sys` with no policies attached.
-- This is the same posture used in Phase 1.5c for all of our own
-- tables: with RLS on and no policies, the table is invisible to the
-- `anon` and `authenticated` roles through the API. The `postgres`
-- owner and the `service_role` (BYPASSRLS) retain full access, and
-- the PostGIS functions inside the database (e.g. ST_Transform) that
-- read spatial_ref_sys internally continue to work because they run
-- with definer or owner privileges.
--
-- Why not move PostGIS to its own schema instead
-- -----------------------------------------------
-- A cleaner long-term fix is `ALTER EXTENSION postgis SET SCHEMA extensions`
-- which also resolves the WARN-level `extension_in_public` and
-- `*_security_definer_function_executable` (st_estimatedextent) lints in
-- one move. That is deferred to a future migration because it touches
-- every object that references PostGIS types and warrants a separate,
-- carefully scoped change. This migration focuses solely on closing the
-- single ERROR-level finding.
--
-- Idempotency
-- -----------
-- ENABLE ROW LEVEL SECURITY is idempotent in PostgreSQL — re-running on
-- a table that already has RLS enabled is a no-op. Safe to re-apply.
--
-- Rollback
-- --------
-- ALTER TABLE public.spatial_ref_sys DISABLE ROW LEVEL SECURITY;
--
-- Verification
-- ------------
-- After this migration, the Supabase advisor (security) should no longer
-- list any ERROR-level findings. The 40 × INFO `rls_enabled_no_policy`
-- entries for our own tables remain by design (private-mode posture per
-- the v3.0-draft Containment Note).

ALTER TABLE public.spatial_ref_sys ENABLE ROW LEVEL SECURITY;
